// The raw HTML tower and Vite overview share one terrain implementation.
// Only the import path differs: both must use their owning renderer's Three.js instance.
import { readFile, writeFile } from "node:fs/promises";
import ts from "typescript";
const input = new URL("../src/overview/terrain.ts", import.meta.url);
const source = (await readFile(input, "utf8")).replace(
  'from "three180"',
  'from "/vendor/three/build/three.module.js"',
);
const { outputText } = ts.transpileModule(source, {
  compilerOptions: {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ES2022,
  },
});
await writeFile(
  new URL("../candidates/tower-terrain.generated.js", import.meta.url),
  "// Generated by scripts/build-tower-terrain.mjs from src/overview/terrain.ts.\n" +
    outputText,
);
